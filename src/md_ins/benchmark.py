"""Harmonic benchmark for the trajectory-to-pDOS pipeline.

This module bridges ASE calculators, Phonopy force constants, and Euphonic
spectral calculations to validate the MD-derived pDOS of a Lennard-Jones FCC
argon crystal against the harmonic phonon density of states.

The benchmark is intentionally self-contained: it computes harmonic force
constants via finite displacements (Phonopy), ingests them into Euphonic to
obtain a reference harmonic phonon DOS, runs a short ASE NVE trajectory at low
temperature, and computes the MD pDOS with the in-house correlation engine.

Cross-method spectral agreement is hard to assert tightly, so the public
``run_benchmark`` returns both spectra plus detected peaks for human review
(see the comparison plots in the project README).  The accompanying test is
*regression based*: with a fixed random seed the pipeline is deterministic and
the test pins the peak locations to recorded baselines rather than requiring
fine agreement between the MD and harmonic spectra.
"""

from __future__ import annotations

import tempfile
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from ase import Atoms, units
from ase.build import bulk
from ase.calculators.lj import LennardJones
from ase.md.velocitydistribution import (
    Stationary,
    ZeroRotation,
    force_temperature,
    thermalize_momenta,
)
from ase.md.verlet import VelocityVerlet
from euphonic import ForceConstants, ureg
from phonopy import Phonopy
from phonopy.file_IO import write_FORCE_CONSTANTS
from phonopy.structure.atoms import PhonopyAtoms
from scipy.ndimage import gaussian_filter1d
from scipy.signal import find_peaks

from md_ins.correlation import calculate_pdos
from md_ins.trajectory import TrajectoryData, calculate_kinetic_temperature

# Lennard-Jones argon parameters (matching the OpenSpec design).
ARGON_EPSILON = 0.01042  # eV
ARGON_SIGMA = 3.4  # Angstrom
ARGON_LATTICE = 5.26  # Angstrom (FCC cubic cell)


def make_lj_calculator(
    epsilon: float = ARGON_EPSILON,
    sigma: float = ARGON_SIGMA,
    cutoff_factor: float = 3.0,
) -> LennardJones:
    """Return an ASE Lennard-Jones calculator for the argon potential."""
    return LennardJones(epsilon=epsilon, sigma=sigma, rc=cutoff_factor * sigma)


def ase_to_phonopy_atoms(atoms: Atoms) -> PhonopyAtoms:
    """Convert an ASE :class:`~ase.atoms.Atoms` to :class:`PhonopyAtoms`."""
    return PhonopyAtoms(
        symbols=atoms.get_chemical_symbols(),
        scaled_positions=atoms.get_scaled_positions(),
        cell=atoms.get_cell().array,
    )


def phonopy_atoms_to_ase(
    cell: PhonopyAtoms, calculator: LennardJones | None = None
) -> Atoms:
    """Convert a :class:`PhonopyAtoms` (e.g. a displaced supercell) back to an
    ASE :class:`Atoms` object, optionally attaching a calculator."""
    atoms = Atoms(
        symbols=cell.symbols,
        scaled_positions=cell.scaled_positions,
        cell=cell.cell,
        pbc=True,
    )
    atoms.calc = calculator
    return atoms


def compute_force_constants(
    atoms: Atoms,
    supercell_matrix,
    calculator_factory=make_lj_calculator,
    *,
    displacement: float = 0.01,
    symprec: float = 1e-5,
) -> Phonopy:
    """Compute harmonic force constants with a lightweight ASE-to-Phonopy wrapper.

    Finite displacements are generated by Phonopy; supercell forces are
    evaluated with the ASE Lennard-Jones calculator (no Calorine dependency).
    The returned :class:`Phonopy` object has ``force_constants`` populated and
    symmetrised.
    """
    unitcell = ase_to_phonopy_atoms(atoms)
    phonon = Phonopy(
        unitcell,
        supercell_matrix=np.asarray(supercell_matrix),
        primitive_matrix="P",
        symprec=symprec,
    )
    phonon.generate_displacements(distance=displacement)

    forces_set = []
    for displaced in phonon.supercells_with_displacements:
        calc = calculator_factory()
        supercell_atoms = phonopy_atoms_to_ase(displaced, calc)
        forces_set.append(supercell_atoms.get_forces())

    phonon.forces = forces_set
    phonon.produce_force_constants(show_drift=False)
    phonon.symmetrize_force_constants()
    return phonon


def make_qgrid(n: int) -> tuple[np.ndarray, np.ndarray]:
    """Return a uniform q-point grid (including Gamma) with equal weights.

    ``n`` divisions along each reciprocal axis yields ``n**3`` points at
    ``[0, 1/n, ..., (n-1)/n]`` in fractional coordinates.
    """
    axes = np.arange(n) / n
    qpoints = np.array(
        [[i, j, k] for i in axes for j in axes for k in axes], dtype=float
    )
    weights = np.ones(len(qpoints), dtype=float)
    return qpoints, weights


def compute_harmonic_dos(
    phonon: Phonopy,
    qpoints: np.ndarray,
    weights: np.ndarray,
    dos_bins_mev: np.ndarray | None = None,
    *,
    workdir: str | Path | None = None,
) -> tuple[np.ndarray, np.ndarray, float]:
    """Ingest Phonopy force constants into Euphonic and compute the harmonic
    phonon DOS over the supplied q-point grid.

    Returns ``(energies_mev, dos_per_mev, band_max_mev)`` where ``energies_mev``
    are the bin centres and ``dos_per_mev`` the density.  ``band_max_mev`` is the
    highest phonon frequency found.
    """
    if dos_bins_mev is None:
        dos_bins_mev = np.arange(0.0, 12.0, 0.02)

    owns_workdir = workdir is None
    if owns_workdir:
        workdir = Path(tempfile.mkdtemp(prefix="md_ins_phonopy_"))
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)

    write_FORCE_CONSTANTS(
        phonon.force_constants, filename=str(workdir / "FORCE_CONSTANTS")
    )
    phonon.save(
        filename=str(workdir / "phonopy.yaml"), settings={"force_constants": True}
    )

    force_constants = ForceConstants.from_phonopy(path=str(workdir))
    modes = force_constants.calculate_qpoint_phonon_modes(
        qpoints, weights=weights, asr="reciprocal", use_c=True
    )
    spectrum = modes.calculate_dos(dos_bins_mev * ureg("meV"))

    energies = spectrum.get_bin_centres().to("meV").magnitude
    dos = spectrum.y_data.to("1/meV").magnitude
    band_max = float(modes.frequencies.to("meV").magnitude.max())
    return energies, dos, band_max


def run_argon_md(
    supercell=(4, 4, 4),
    *,
    temperature_k: float = 10.0,
    timestep_fs: float = 2.0,
    n_steps: int = 10000,
    seed: int = 42,
    calculator_factory=make_lj_calculator,
    lattice: float = ARGON_LATTICE,
) -> TrajectoryData:
    """Run a short ASE velocity-Verlet NVE trajectory of FCC argon.

    Momenta are thermalised to ``temperature_k`` (after removing centre-of-mass
    drift and net rotation) and the trajectory velocities are returned in the
    standard :class:`TrajectoryData` representation.
    """
    atoms = bulk("Ar", "fcc", a=lattice, cubic=True).repeat(supercell)
    atoms.calc = calculator_factory()

    rng = np.random.default_rng(seed)
    thermalize_momenta(atoms, temperature_k, exact_temperature=True, rng=rng)
    Stationary(atoms)
    ZeroRotation(atoms)
    force_temperature(atoms, temperature_k)

    dynamics = VelocityVerlet(atoms, timestep_fs * units.fs, logfile=None)
    velocities_ase = np.empty((n_steps, len(atoms), 3))
    for step in range(n_steps):
        dynamics.run(1)
        velocities_ase[step] = atoms.get_velocities()

    velocities = velocities_ase * units.fs  # ASE unit -> Angstrom / fs
    return TrajectoryData(
        velocities=velocities,
        symbols=atoms.get_chemical_symbols(),
        masses=atoms.get_masses(),
        timestep_fs=timestep_fs,
        cell=atoms.get_cell().array,
    )


def detect_peaks(
    energies_mev: np.ndarray,
    dos: np.ndarray,
    *,
    smooth_sigma_mev: float = 0.3,
    min_prominence_frac: float = 0.15,
    energy_min_mev: float = 0.3,
    max_peaks: int = 5,
) -> np.ndarray:
    """Detect a few prominent spectral peaks via Gaussian smoothing + thresholding.

    The spectrum is smoothed by a Gaussian of width ``smooth_sigma_mev`` and
    peaks are selected by ``scipy.signal.find_peaks`` with a prominence
    threshold relative to the maximum.  Returns the peak energies (meV) sorted
    by descending prominence, truncated to ``max_peaks``.
    """
    energies_mev = np.asarray(energies_mev, dtype=float)
    dos = np.asarray(dos, dtype=float)
    if energies_mev.shape[0] < 2:
        return np.array([], dtype=float)
    bin_width = energies_mev[1] - energies_mev[0]
    smoothed = gaussian_filter1d(dos, smooth_sigma_mev / bin_width)

    valid = energies_mev >= energy_min_mev
    if not valid.any():
        return np.array([], dtype=float)
    prominence = min_prominence_frac * smoothed[valid].max()
    peaks, properties = find_peaks(smoothed, prominence=prominence)

    # restrict to the valid energy region and order by prominence
    keep = peaks[energies_mev[peaks] >= energy_min_mev]
    order = np.argsort(properties["prominences"][: len(keep)])[::-1]
    kept = keep[order][:max_peaks]
    return energies_mev[kept]


@dataclass
class BenchmarkResult:
    """Container for a complete benchmark run."""

    harmonic_energies_mev: np.ndarray
    harmonic_dos: np.ndarray
    harmonic_band_max_mev: float
    harmonic_peaks_mev: np.ndarray
    md_energies_mev: np.ndarray
    md_dos: np.ndarray
    md_peaks_mev: np.ndarray
    trajectory_temperature_k: float
    supercell: tuple[int, int, int]


def run_benchmark(
    supercell=(4, 4, 4),
    *,
    temperature_k: float = 10.0,
    timestep_fs: float = 2.0,
    n_steps: int = 10000,
    seed: int = 42,
    harmonic_dos_bins_mev: np.ndarray | None = None,
    smooth_sigma_mev: float = 0.3,
) -> BenchmarkResult:
    """Run the closed-loop Lennard-Jones argon benchmark.

    Computes the harmonic phonon DOS (Euphonic, on the q-grid matching the MD
    supercell so both spectra sample the same reciprocal-space points) and the
    MD-derived pDOS, and detects prominent peaks in each for comparison.
    """
    supercell = tuple(supercell)
    atoms = bulk("Ar", "fcc", a=ARGON_LATTICE, cubic=True)

    phonon = compute_force_constants(atoms, np.diag(supercell))
    qpoints, weights = make_qgrid(supercell[0])
    harm_energies, harm_dos, band_max = compute_harmonic_dos(
        phonon, qpoints, weights, dos_bins_mev=harmonic_dos_bins_mev
    )
    harm_peaks = detect_peaks(
        harm_energies, harm_dos, smooth_sigma_mev=smooth_sigma_mev
    )

    trajectory = run_argon_md(
        supercell,
        temperature_k=temperature_k,
        timestep_fs=timestep_fs,
        n_steps=n_steps,
        seed=seed,
    )
    pdos = calculate_pdos(
        trajectory.velocities,
        trajectory.timestep_fs,
        symbols=trajectory.symbols,
        window="hann",
    )
    t_traj = calculate_kinetic_temperature(trajectory)

    md_peaks = detect_peaks(
        pdos.energies_mev, pdos.total_dos, smooth_sigma_mev=smooth_sigma_mev
    )

    return BenchmarkResult(
        harmonic_energies_mev=harm_energies,
        harmonic_dos=harm_dos,
        harmonic_band_max_mev=band_max,
        harmonic_peaks_mev=harm_peaks,
        md_energies_mev=pdos.energies_mev,
        md_dos=pdos.total_dos,
        md_peaks_mev=md_peaks,
        trajectory_temperature_k=t_traj,
        supercell=supercell,
    )


def plot_comparison(result: BenchmarkResult, savepath: str | Path | None = None):
    """Plot the harmonic and MD density of states side by side for review.

    Requires matplotlib (available as an ASE/Phonopy dependency).  When
    ``savepath`` is given the figure is written there and closed; otherwise the
    figure is returned.
    """
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # Normalize both spectra to unit area so the shapes are comparable on one
    # axis regardless of their native scaling (harmonic total DOS integrates to
    # the number of modes; the MD pDOS is normalised to 1).
    he = result.harmonic_energies_mev
    hd = result.harmonic_dos / np.trapezoid(result.harmonic_dos, he)
    me = result.md_energies_mev
    md = result.md_dos / np.trapezoid(result.md_dos, me)

    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=False)

    ax = axes[0]
    ax.plot(he, hd, color="tab:blue", lw=1.0)
    for peak in result.harmonic_peaks_mev:
        ax.axvline(peak, color="tab:blue", ls=":", alpha=0.6)
    ax.set_title("Harmonic phonon DOS (Euphonic)")
    ax.set_xlabel("Energy (meV)")
    ax.set_ylabel("DOS (normalised)")
    ax.set_xlim(0, max(result.harmonic_band_max_mev * 1.1, 10))

    ax = axes[1]
    ax.plot(me, md, color="tab:orange", lw=1.0)
    for peak in result.md_peaks_mev:
        ax.axvline(peak, color="tab:orange", ls=":", alpha=0.6)
    ax.set_title(f"MD pDOS (T_traj={result.trajectory_temperature_k:.1f} K)")
    ax.set_xlabel("Energy (meV)")
    ax.set_ylabel("pDOS (normalised)")
    ax.set_xlim(0, max(result.harmonic_band_max_mev * 1.1, 10))

    fig.tight_layout()
    if savepath is not None:
        fig.savefig(str(savepath), dpi=130)
        plt.close(fig)
    return fig
